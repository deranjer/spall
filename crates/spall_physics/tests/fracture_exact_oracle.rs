//! Independent exact-rational projected-corner oracle, generated offline with
//! Python fractions.Fraction from canonical binary32 inputs. No interval or
//! support-radius implementation is reused. Boundary contacts are excluded.
use spall_core::{GlobalCell, MaterialId, VolumeId};
use spall_physics::fracture::{
    FractureError, FracturePartSnapshot, FractureSnapshot, FractureSnapshotToken,
};
use spall_physics::{OccupancyGrid, PartTransform, SourcePart, prepare_fracture};

#[test]
fn rational_corner_oracle_rejects_false_welds_and_false_separation() {
    let mut classified = 0;
    let mut ambiguous = 0;
    for &(bits, expected) in CASES {
        let v = bits.map(f32::from_bits);
        let parts = (0..2)
            .map(|i| FracturePartSnapshot {
                source: SourcePart {
                    part_id: i as u32 + 1,
                    parent_id: None,
                    volume_id: VolumeId::new(i as u64 + 8100).unwrap(),
                    source_revision: 1,
                    grid: OccupancyGrid::from_solid_mask(
                        GlobalCell::new(0, 0, 0),
                        [1, 1, 1],
                        vec![true],
                        vec![MaterialId(1)],
                    )
                    .unwrap(),
                    cell_m: 1.0,
                    local_transform: PartTransform::IDENTITY,
                },
                root_local_pose: PartTransform {
                    translation_m: if i == 0 { [0.0; 3] } else { [v[4], v[5], 0.0] },
                    rotation_xyzw: [0.0, 0.0, v[i * 2], v[i * 2 + 1]],
                },
            })
            .collect();
        let snapshot = FractureSnapshot {
            token: FractureSnapshotToken {
                corpse_key: 8100,
                component_key: None,
                topology_revision: 1,
                pose_epoch: 1,
                source_generation: 1,
            },
            parts,
        };
        match prepare_fracture(&snapshot) {
            Ok(plan) => {
                assert_eq!(
                    plan.components.len(),
                    usize::from(expected),
                    "input {bits:?}"
                );
                classified += 1;
            }
            Err(FractureError::AmbiguousContact { .. }) => ambiguous += 1,
            Err(other) => panic!("unexpected {other:?} for {bits:?}"),
        }
    }
    assert!(
        classified > CASES.len() / 2,
        "insufficient classified coverage: {classified}"
    );
    eprintln!(
        "exact-rational corner oracle: {classified} classified, {ambiguous} conservative ambiguities, {} total",
        CASES.len()
    );
}

